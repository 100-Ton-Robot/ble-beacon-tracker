#!/usr/bin/env python3
"""ngspice runs of the unified power + LED board (hand build templates page 8).

Reads sim/parameters.csv (model estimates and datasheet values) and the board's own values from
common/ and builds/hand/parameters.csv, writes netlists with those values into out/, runs ngspice in batch mode,
and writes out/summary.md (figures and checks) plus out/*.dat traces and, with matplotlib, out/*.png.

    python3 sim/run_sim.py            # all cases
    python3 sim/run_sim.py --no-plots

Needs ngspice (apt install ngspice) and numpy; matplotlib only for the plots.
Exit status 1 if a check fails. The strip-short case is reported as a warning, not a failure:
it describes the design (the splitter current-limits before the fuse can open), not a broken run.
"""
import argparse
import os
import shutil
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "out")
sys.path.insert(0, os.path.join(ROOT, "common"))
import params  # noqa: E402  (common/params.py: one loader for every CSV)

SCALE = {"uF": 1e-6, "pF": 1e-12, "nH": 1e-9, "uH": 1e-6, "ns": 1e-9, "uA": 1e-6, "mA": 1e-3}


def sim_values():
    v = {}
    for r in params.rows(os.path.join(HERE, "parameters.csv")):
        v[r["name"]] = params.parse(r["value"]) * SCALE.get(r["unit"], 1)
    d = params.load(build="hand")       # the LED ring and unified board are hand-build add-ons
    white_ma, dark_ma = d["LED_PIXEL_MA"]
    v.update(LED_CAP=d["LED_CAP_UF"] * 1e-6, LED_BYPASS=d["LED_BYPASS_UF"] * 1e-6, LED_SERIES=d["LED_SERIES_OHM"],
             LED_PIXELS=d["LED_PIXELS"], ILED_WHITE=d["LED_PIXELS"] * white_ma * 1e-3,
             ILED_DARK=d["LED_PIXELS"] * dark_ma * 1e-3, PULLDOWN=d["UNI_PULLDOWN_OHM"], FUSE_A=d["LED_FUSE_A"],
             SPLIT_RATED=d["LED_SUPPLY_A"][0])
    return v


CASE_DEFAULTS = dict(TRAMP=3e-3, TPLUG=0, TLED=1, DUTY=1.0, TSHORT=1, RSHORT=1e6, SHIFT=1)

# name, netlist, case parameters, .tran line, traces
CASES = [
    ("power_up", "power.cir", {}, "1u 15m 0 2u uic", "v(vin) v(esp) v(strip) i(vsens)"),
    ("hot_plug", "power.cir", dict(TPLUG=1e-3, TRAMP=10e-6), "0.2u 10m 0 0.2u uic", "v(vin) v(esp) i(vcabs)"),
    ("full_white", "power.cir", dict(TLED=8e-3), "1u 20m 0 2u uic", "v(vin) v(esp) v(xi) v(strip) i(vfuse)"),
    ("half_pwm", "power.cir", dict(TLED=8e-3, DUTY=0.5), "1u 20m 0 2u uic", "v(vin) v(esp) v(xi) v(strip) i(vfuse)"),
    ("strip_short", "power.cir", dict(TSHORT=8e-3, RSHORT=None), "1u 40m 0 2u uic", "v(vin) v(esp) i(vfuse) i(vsens)"),
    ("data_shift", "data.cir", {}, "0.1n 12u", "v(gp) v(a1) v(y) v(din)"),
    ("data_direct", "data.cir", dict(SHIFT=0), "0.1n 12u", "v(gp) v(a1) v(y) v(din)"),
    ("boot_pulldown", "boot.cir", {}, "10n 2m uic", "v(a1) v(din)"),
    ("boot_floating", "boot.cir", dict(PULLDOWN=1e12), "10n 2m uic", "v(a1) v(din)"),
]


def run_case(name, netlist, case, tran, traces, v):
    p = dict(v, **CASE_DEFAULTS)
    p.update({k: (v["SHORT_R"] if (k == "RSHORT" and x is None) else x) for k, x in case.items()})
    inc = os.path.join(OUT, f"{name}.inc")
    with open(inc, "w") as f:
        f.write("* generated by run_sim.py from sim/parameters.csv and the hand build's parameter files\n")
        for k in sorted(p):
            f.write(f".param {k}={p[k]:.6g}\n")
    src = open(os.path.join(HERE, "netlists", netlist)).read().replace(".include params.inc", f".include {inc}")
    dat = os.path.join(OUT, f"{name}.dat")
    src = src.replace(".end\n", f".tran {tran}\n.control\nrun\nset wr_singlescale\nset wr_vecnames\n"
                                f"wrdata {dat} {traces}\n.endc\n.end\n")
    cir = os.path.join(OUT, f"{name}.cir")
    open(cir, "w").write(src)
    r = subprocess.run(["ngspice", "-b", cir], capture_output=True, text=True)
    if r.returncode or not os.path.exists(dat):
        sys.exit(f"ngspice failed on {name}:\n{r.stdout[-1500:]}\n{r.stderr[-1500:]}")
    d = np.genfromtxt(dat, names=True)
    return {k.lower(): d[k] for k in d.dtype.names}


def highs(t, v, level):
    up = np.diff((v > level).astype(int))
    a, b = t[1:][up == 1], t[1:][up == -1]
    return [(y - x) * 1e9 for x, y in zip(a, b)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-plots", action="store_true")
    args = ap.parse_args()
    if not shutil.which("ngspice"):
        sys.exit("ngspice not found (apt install ngspice)")
    os.makedirs(OUT, exist_ok=True)
    v = sim_values()
    R = {n: run_case(n, nl, c, tr, tc, v) for n, nl, c, tr, tc in CASES}

    rows, fails, warns = [], 0, 0

    def check(what, value, ok, note=""):
        nonlocal fails
        fails += not ok
        rows.append((what, value, "pass" if ok else "FAIL", note))

    d = R["power_up"]
    check("Power-up: peak splitter current", f"{np.abs(d['ivsens']).max():.2f} A", True, "PoE soft start, strip dark")
    d = R["hot_plug"]
    check("Hot plug: peak cord current", f"{np.abs(d['ivcabs']).max():.1f} A", True,
          "plugging into a live splitter; connect the board before the PoE cable")
    check("Hot plug: peak 5 V", f"{d['vvin'].max():.3f} V", d["vvin"].max() < 5.5, "U1 and XIAOs want 5.5 V or less")
    for n, label in (("full_white", "Full white"), ("half_pwm", "Half brightness, PWM in phase")):
        d = R[n]
        late = d["time"] > 18e-3
        esp, strip = d["vesp"][late].min(), d["vstrip"][late].min()
        check(f"{label}: ESP32 / XIAO feed, lowest", f"{esp:.3f} V", esp >= 4.75, "USB VBUS minimum 4.75 V")
        check(f"{label}: strip end, lowest", f"{strip:.3f} V", strip >= 4.5, "")
        check(f"{label}: fuse current peak", f"{np.abs(d['ivfuse']).max():.2f} A", True, "brief ring at the step")
    d = R["strip_short"]
    t, i = d["time"], d["ivfuse"]
    first = (t > 8e-3) & (t < 9e-3)
    late = t > 20e-3
    ratio = np.abs(i[late]).mean() / v["FUSE_A"]
    rows.append(("Strip short: capacitor dump through the fuse", f"{np.abs(i).max():.1f} A, "
                 f"I2t {np.trapezoid(i[first] ** 2, t[first]):.3f} A2s", "info", "first ms"))
    rows.append(("Strip short: steady fuse current", f"{np.abs(i[late]).mean():.2f} A ({ratio:.0%} of rating)",
                 "WARN" if ratio < 2 else "pass",
                 "below 200% the 251 series has no maximum opening time; splitter limits first. "
                 "Accepted risk (user, 2026-11-20): a strip short reboots the mast"))
    warns += ratio < 2
    rows.append(("Strip short: 5 V rail", f"{d['vvin'][late].mean():.2f} V", "WARN" if d["vvin"][late].mean() < 4 else "pass",
                 "ESP32 and XIAOs brown out"))
    warns += d["vvin"][late].mean() < 4
    for n, label in (("data_shift", "Data through U1"), ("data_direct", "Data without U1 (3.3 V)")):
        d = R[n]
        for vdd in (5.0, 4.73):
            hs = highs(d["time"], d["vdin"], v["DIN_VIH"] * vdd)
            ok = len(hs) == 8 and all(abs(h - w) < 150 for h, w in zip(hs, (800, 400, 800, 800, 400, 400, 800, 400)))
            res = " ".join(f"{h:.0f}" for h in hs) + " ns" if hs else "none"
            if n == "data_shift":
                check(f"{label}: highs at DIN, VDD {vdd} V", res, ok, "need 800/400 ns within 150 ns")
            else:
                rows.append((f"{label}: highs at DIN, VDD {vdd} V", res, "info", "no valid highs: why U1 is fitted"))
    d = R["boot_pulldown"]
    check("Boot, GPIO1 floating, with R2: DIN highest", f"{d['vdin'].max():.3f} V", d["vdin"].max() < 1.0, "")
    d = R["boot_floating"]
    on = d["time"][np.argmax(d["vdin"] > 2.5)] * 1e6 if d["vdin"].max() > 2.5 else None
    rows.append(("Boot, GPIO1 floating, no R2: DIN goes high", f"after {on:.1f} us" if on else "never", "info",
                 "why R2 is fitted"))

    with open(os.path.join(OUT, "summary.md"), "w") as f:
        f.write("# Unified board simulation\n\nGenerated by `sim/run_sim.py`. Model values: `sim/parameters.csv`; "
                "board values: `common/parameters.csv`, `builds/hand/parameters.csv`.\n\n| Check | Result | Status | Note |\n|---|---|---|---|\n")
        for r in rows:
            f.write("| " + " | ".join(r) + " |\n")
        f.write(f"\n{fails} failed, {warns} warnings.\n")
    for r in rows:
        print(f"{r[2]:>5}  {r[0]}: {r[1]}")
    print(f"{fails} failed, {warns} warnings. Summary: {os.path.relpath(os.path.join(OUT, 'summary.md'), ROOT)}")

    if not args.no_plots:
        try:
            plots(R)
        except ImportError:
            print("matplotlib not installed: no plots")
    sys.exit(1 if fails else 0)


def plots(R):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    spec = [
        ("full_white", 1e3, "ms", (7, 12), [("vesp", "ESP32 feed"), ("vstrip", "strip end")], "V"),
        ("half_pwm", 1e3, "ms", (7, 15), [("vesp", "ESP32 feed"), ("vstrip", "strip end")], "V"),
        ("strip_short", 1e3, "ms", (7, 20), [("vvin", "5 V rail"), ("ivfuse", "fuse current (A)")], ""),
        ("hot_plug", 1e3, "ms", (0.95, 1.25), [("vvin", "5 V rail"), ("ivcabs", "cord current (A)")], ""),
        ("data_shift", 1e6, "us", (0.8, 10.6), [("vgp", "GPIO1"), ("vdin", "DIN via U1")], "V"),
        ("data_direct", 1e6, "us", (0.8, 10.6), [("vgp", "GPIO1"), ("vdin", "DIN direct")], "V"),
        ("boot_pulldown", 1e6, "us", (0, 40), [("va1", "U1 input"), ("vdin", "DIN")], "V"),
        ("boot_floating", 1e6, "us", (0, 40), [("va1", "U1 input"), ("vdin", "DIN")], "V"),
    ]
    for name, k, unit, (x0, x1), traces, yl in spec:
        d = R[name]
        t = d["time"] * k
        m = (t >= x0) & (t <= x1)
        fig, ax = plt.subplots(figsize=(7, 3.2), dpi=110)
        for key, lab in traces:
            y = np.abs(d[key]) if key.startswith("i") else d[key]
            ax.plot(t[m], y[m], label=lab, lw=1.4)
        ax.set_xlabel(unit)
        ax.set_ylabel(yl)
        ax.set_title(name.replace("_", " "))
        ax.grid(alpha=.3)
        ax.legend(loc="best", fontsize=8)
        fig.tight_layout()
        fig.savefig(os.path.join(OUT, f"{name}.png"))
        plt.close(fig)


if __name__ == "__main__":
    main()
