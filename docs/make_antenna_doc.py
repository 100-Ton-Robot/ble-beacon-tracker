#!/usr/bin/env python3
"""Write docs/ANTENNA_SELECTION.md from the parameters and the committed RF results.

    python3 docs/make_antenna_doc.py

Every number in the doc comes from here, read at run time:
  - common/parameters.csv (via common/params.py): frequency, face and core, duck spacings, holes, antenna specs;
  - common/layout.py: derived geometry (r_in, D-hole radius, deck diameter) for each spacing in DECK_VARIANTS;
  - docs/antenna_runs.csv: which RF runs stand for which candidate (label, antenna, spacing, run, bearing folder);
  - rf_model/out/<run>/summary.txt and rf_model/out/<bearing>/summary.txt: match, gain, isolation and bearing error.

The only constant kept here is the speed of light. To add a candidate: run sector_model.py and bearing_sim.py (see
rf_model/README.md), add a row to docs/antenna_runs.csv, rerun this script, commit the doc with the runs.
"""
import csv
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "common"))
import params   # noqa: E402
import layout   # noqa: E402

C = 299_792_458.0          # m/s, physical constant (not a design value, so not in parameters.csv)
OUT = os.path.join(ROOT, "rf_model", "out")
DOC = os.path.join(HERE, "ANTENNA_SELECTION.md")
P = params.load(build="pcb")


def run_summary(run):
    """S11 / Zin at the frequency nearest RF_FREQ, peak gain and direction, isolation to the other sectors."""
    txt = open(os.path.join(OUT, run, "summary.txt")).read()
    best = None
    for m in re.finditer(r"^\s*(\d+) MHz\s+S11\s+(-?[\d.]+) dB\s+Zin\s+([\d.]+)\s+([+-][\d.]+)j", txt, re.M):
        f = float(m.group(1))
        if best is None or abs(f - P["RF_FREQ"]) < abs(best[0] - P["RF_FREQ"]):
            best = (f, float(m.group(2)), float(m.group(3)), float(m.group(4)))
    pk = re.search(r"^peak ([\d.-]+) dBi at az (-?\d+), el (-?\d+) deg", txt, re.M)
    iso = [float(x) for x in re.findall(r"^\s*S\d+: (-?[\d.]+) dB", txt, re.M)]
    return {"f": best[0], "s11": best[1], "zr": best[2], "zx": best[3], "peak": float(pk.group(1)),
            "az": int(pk.group(2)), "el": int(pk.group(3)), "iso": max(iso) if iso else float("nan")}


def bearing(folder, run):
    """Median / 90% / rms bearing error and right-sector share for one run in a bearing_sim.py summary."""
    txt = open(os.path.join(OUT, folder, "summary.txt")).read()
    m = re.search(rf"^{re.escape(run)}\s+(\d+)\s+(\d+)\s+(\d+)\s+\(.*?\)\s+([\d.]+)%", txt, re.M)
    if not m:
        raise SystemExit(f"{run} not in {folder}/summary.txt")
    setup = re.search(r"^fading .*$", txt, re.M).group(0)
    return {"med": int(m.group(1)), "p90": int(m.group(2)), "rms": int(m.group(3)), "sector": float(m.group(4)),
            "setup": setup}


def main():
    f = P["RF_FREQ"] * 1e6
    lam = C / f * 1000.0                       # mm
    spacings = [float(s) for s in P["DECK_VARIANTS"]]
    rows = list(csv.DictReader(open(os.path.join(HERE, "antenna_runs.csv"))))
    for r in rows:
        r.update(run_summary(r["run"]))
        r.update(bearing(r["bearing"], r["run"]))
    ranked = sorted(rows, key=lambda r: (r["med"], r["p90"], -r["sector"]))
    best = ranked[0]

    out = []
    w = out.append
    w("# Antenna selection")
    w("")
    w("<!-- Generated by docs/make_antenna_doc.py from common/parameters.csv, common/layout.py, docs/antenna_runs.csv "
      "and rf_model/out. Do not edit by hand: change the inputs and rerun the script. -->")
    w("")
    w("Which antenna to put on each sector, and how far in front of its face. Every value below is read from "
      "`common/parameters.csv` or worked out from it, and every result from the committed RF model runs "
      "(`rf_model/out`), when `docs/make_antenna_doc.py` last ran.")
    w("")
    w("## Recommendation")
    w("")
    w(f"**{best['label']}.** It has the lowest bearing error of the modelled candidates: {best['med']} deg median, "
      f"{best['p90']} deg at 90%, the right sector {best['sector']:.0f}% of the time. Ranking (median, then 90%):")
    w("")
    w("| # | Candidate | Median | 90% | Right sector |")
    w("| --- | --- | --- | --- | --- |")
    for k, r in enumerate(ranked, 1):
        w(f"| {k} | {r['label']} | {r['med']} deg | {r['p90']} deg | {r['sector']:.1f}% |")
    w("")
    duck = {float(r["spacing_mm"]): r for r in rows if r["antenna"] == "duck"}
    stub = {float(r["spacing_mm"]): r for r in rows if r["antenna"] == "stubby"}
    if len(duck) == 2 and len(stub) == 2:
        s0, s1 = sorted(duck)
        w(f"- **Spacing:** {s0:g} mm is never worse than {s1:g} mm for bearing here. For the ducks it is close "
          f"({duck[s0]['med']} / {duck[s0]['p90']} against {duck[s1]['med']} / {duck[s1]['p90']} deg), and {s1:g} mm "
          f"matches better (S11 {duck[s1]['s11']:.1f} dB against {duck[s0]['s11']:.1f} dB at {duck[s0]['f']:g} MHz). "
          f"For the stubby it is clearly better ({stub[s0]['med']} / {stub[s0]['p90']} against "
          f"{stub[s1]['med']} / {stub[s1]['p90']} deg).")
        w(f"- **Antenna type:** a half-wave duck hanging in front of the face beats a quarter-wave stubby by about "
          f"{stub[s0]['med'] / duck[s0]['med']:.1f}x in median error at {s0:g} mm. The stubby uses the deck as its "
          f"ground plane, so its beam stays broad and tilts down (peak at el {stub[s0]['el']} deg); the duck's peak is "
          f"at el {duck[s0]['el']} deg, straight out from its face.")
    w("")
    w("## Candidates")
    w("")
    w("| Candidate | What it is | Mount | Status |")
    w("| --- | --- | --- | --- |")
    w(f"| Rubber duck (HiRO H50327) | half-wave sleeve dipole, {P['ANT_DUCK_LENGTH']:g} mm, {P['ANT_DUCK_GAIN']:g} dBi, "
      f"RP-SMA | D hole, hanging below the deck in front of the face | modelled |")
    w(f"| Stubby | quarter-wave monopole (shortened, inside a {P['ANT_STUBBY_RADOME']:g} mm radome), "
      f"{P['ANT_STUBBY_LENGTH']:g} mm end to end, {P['ANT_STUBBY_GAIN']:g} dBi, RP-SMA | D hole, the deck as its "
      f"ground plane | modelled as a straight wire of the same length |")
    w(f"| Printed fin | printed half-wave dipole on 1 mm FR-4, standing out from the face | the face's centre "
      f"{P['DIPOLE_HOLE']:g} mm hole (`DIPOLE_HOLE`) | its model isn't in this repo yet |")
    w(f"| Patch | flat patch panel | P hole ({P['PATCH_OFFSET']:g} mm off the face, `PATCH_OFFSET`) or P2 | not "
      f"modelled |")
    w("")
    w("## Results")
    w("")
    w(f"Bearing simulation setup: {best['setup']}.")
    w("")
    w(f"| Candidate | Spacing | S11 at {best['f']:g} MHz | Zin (model) | Peak gain | Peak direction | Isolation | "
      f"Median | 90% | rms | Right sector | Run |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        w(f"| {r['label']} | {float(r['spacing_mm']):g} mm | {r['s11']:.1f} dB | {r['zr']:.0f} {r['zx']:+.0f}j ohm | "
          f"{r['peak']:.1f} dBi | az {r['az']}, el {r['el']} deg | {r['iso']:.0f} dB | {r['med']} deg | "
          f"{r['p90']} deg | {r['rms']} deg | {r['sector']:.1f}% | `rf_model/out/{r['run']}` |")
    w("")
    for r in rows:
        w(f"- {r['label']}: {r['notes']}.")
    w("")
    w("## Formulas")
    w("")
    w(f"Speed of light c = {C:.0f} m/s (the one constant in the script). Frequency f = `RF_FREQ` = "
      f"{P['RF_FREQ']:g} MHz.")
    w("")
    w("| Symbol | Formula | Value |")
    w("| --- | --- | --- |")
    w(f"| lambda | c / f | {lam:.1f} mm |")
    w(f"| lambda / 4 | quarter wave (monopole) | {lam / 4:.1f} mm |")
    w(f"| lambda / 2 | half wave (dipole) | {lam / 2:.1f} mm |")
    w(f"| L_mono | 0.95 x lambda / 4 (`sector_model.py` default monopole) | {0.95 * lam / 4:.1f} mm |")
    w(f"| L_dip | 0.95 x lambda / 2 (`sector_model.py` default dipole) | {0.95 * lam / 2:.1f} mm |")
    w(f"| duck | ANT_DUCK_LENGTH / lambda | {P['ANT_DUCK_LENGTH'] / lam:.2f} lambda |")
    w(f"| stubby | ANT_STUBBY_LENGTH / (lambda / 4) | {P['ANT_STUBBY_LENGTH'] / (lam / 4):.2f} of a quarter wave |")
    w(f"| face | FACE_WIDTH x FACE_H in wavelengths | {P['FACE_WIDTH'] / lam:.2f} x {P['FACE_H'] / lam:.2f} lambda |")
    w(f"| duck feed | DUCK_FEED_DEPTH below the deck (model) | {P['DUCK_FEED_DEPTH']:g} mm |")
    w("")
    w("Per duck spacing d (`DECK_VARIANTS`). AF is the image-theory gain of a vertical element at d in front of an "
      "infinite flat reflector, straight out from the face: AF = 2 |sin(2 pi d / lambda)|, in dB 20 log10 AF. It "
      "peaks at d = lambda / 4. The real face is finite and the bearing estimate depends on the beam's shape and "
      "back rejection, not its peak, so AF explains the trend in gain, not the bearing ranking.")
    w("")
    w("| d | d / lambda | Phase 2 pi d / lambda | AF | AF dB | r_D = r_in + d | D_need | D_deck |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for d in spacings:
        L = layout.Layout(d)
        rr = {sym: val for _, sym, _, val, _, _ in L.rows}
        af = 2 * abs(math.sin(2 * math.pi * d / lam))
        w(f"| {d:g} mm | {d / lam:.3f} | {360 * d / lam:.0f} deg | {af:.2f} | {20 * math.log10(af):+.1f} dB | "
          f"{rr['r_D']:.2f} mm | {rr['D_need']:.1f} mm | {rr['D_deck']:.1f} mm |")
    w("")
    L = layout.Layout(spacings[0])
    w("Geometry formulas, from `common/layout.py` (the same rows the hand build's formulas page prints):")
    w("")
    w("| Section | Symbol | Formula | Value | Note |")
    w("| --- | --- | --- | --- | --- |")
    for sec, sym, form, val, unit, note in L.rows:
        if sec in ("TRIANGLE CORE", "ANTENNA HOLES", "DECK") and sym not in ("pipe hole", "r_M3", "D_end"):
            w(f"| {sec.title()} | {sym} | `{form}` | {val:.2f} {unit} | {note.replace(chr(10), ' ')} |")
    w(f"| | | (D hole rows for d = {spacings[0]:g} mm; see the spacing table for the others) | | |")
    w("")
    w("## Updating this doc")
    w("")
    w("1. Change values in `common/parameters.csv` (or a build's file), never in the doc.")
    w("2. New antenna or spacing: run it with `rf_model/sector_model.py` into a new folder (never over an old one), "
      "then `rf_model/bearing_sim.py` with the runs to compare; see `rf_model/README.md`.")
    w("3. Add a row to `docs/antenna_runs.csv` (label, antenna, spacing, run folder, bearing folder, notes).")
    w("4. `python3 docs/make_antenna_doc.py`, then commit the doc with the runs and the CSV.")
    w("")
    with open(DOC, "w") as fh:
        fh.write("\n".join(out))
    print("wrote", DOC)


if __name__ == "__main__":
    main()
